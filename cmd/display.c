/* Helper functions for I2C communication */
static struct udevice *display_dev;

static int display_command(u8 cmd)
{
	u8 buf[2] = {SSD1306_CONTROL_CMD, cmd};
	struct i2c_msg msg;
	struct dm_i2c_chip *chip;

	if (!display_dev)
		return -ENODEV;

	chip = dev_get_parent_plat(display_dev);
	msg.addr = chip->chip_addr;
	msg.flags = 0;
	msg.len = 2;
	msg.buf = buf;

	return dm_i2c_xfer(display_dev, &msg, 1);
}

static int display_data(u8 data)
{
	u8 buf[2] = {SSD1306_CONTROL_DATA, data};
	struct i2c_msg msg;
	struct dm_i2c_chip *chip;

	if (!display_dev)
		return -ENODEV;

	chip = dev_get_parent_plat(display_dev);
	msg.addr = chip->chip_addr;
	msg.flags = 0;
	msg.len = 2;
	msg.buf = buf;

	return dm_i2c_xfer(display_dev, &msg, 1);
}

static int display_init(void)
{
	int ret;

	/* Display off */
	ret = display_command(SSD1306_DISPLAY_OFF);
	if (ret)
		return ret;

	/* Clock divider - divide by 2 for 500kHz I2C clock */
	display_command(SSD1306_CLOCK_DIVIDE);
	display_command(0x81);

	/* Multiplex ratio 1/32 */
	display_command(SSD1306_MULTIPLEX_RATIO);
	display_command(0x1F);

	/* Display offset 0 */
	display_command(SSD1306_DISPLAY_OFFSET);
	display_command(0x00);

	/* Display RAM start line = 0 */
	display_command(SSD1306_START_LINE);

	/* Enable charge pump (internal VCC generation) */
	display_command(SSD1306_CHARGE_PUMP);
	display_command(0x14);  /* Enable */

	/* Segment remap - col 127 mapped to SEG0 */
	display_command(SSD1306_SEG_REMAP_127);

	/* COM scan direction - remapped */
	display_command(SSD1306_COM_SCAN_DOWN);

	/* COM pins configuration */
	display_command(SSD1306_COM_CONFIG);
	display_command(0x02); /* Sequential, left remap */

	/* Contrast */
	display_command(SSD1306_CONTRAST);
	display_command(0xBF);

	/* Precharge period */
	display_command(SSD1306_PRECHARGE);
	display_command(0xF1);

	/* VCOMH deselect level */
	display_command(SSD1306_VCOMH_DESELECT);
	display_command(0x30); /* 0.83 x VCC */

	/* Normal display (not all-on) */
	display_command(SSD1306_ENTIRE_DISPLAY_NORMAL);

	/* Normal display (not inverted) */
	display_command(SSD1306_INVERSION_NORMAL);

	/* Display on */
	ret = display_command(SSD1306_DISPLAY_ON);

	return ret;
}

static int display_clear(void)
{
	int p, i;

	for (p = 0; p < 8; p++) {
		display_command(0x00); /* Lower column */
		display_command(0x10); /* Upper column */
		display_command(0xB0 + p); /* Page */

		for (i = 0; i < 128; i++)
			display_data(0x00);
	}

	return 0;
}

static int display_write_text(const char *text)
{
	const char *c;
	int row = 3;  /* Always write to bottom row */
	int i;

	/* Set position */
	display_command(0x00); /* Lower column */
	display_command(0x10); /* Upper column */
	display_command(0xB0 + row); /* Page */

	/* Clear entire row first */
	for (i = 0; i < 128; i++)
		display_data(0x00);

	/* Reset position to start of row */
	display_command(0x00); /* Lower column */
	display_command(0x10); /* Upper column */
	display_command(0xB0 + row); /* Page */

	/* Write text */
	for (c = text; *c; c++) {
		const oled_digit *d = &font6x8[(int)*c];
		int j;

		for (j = 0; j < d->size; j++)
			display_data(d->data[j]);
	}

	return 0;
}

static int display_draw_logo(void)
{
	int row, col;

	for (row = 0; row < 4; row++) {
		display_command(0x00); /* Lower column */
		display_command(0x10); /* Upper column */
		display_command(0xB0 + row); /* Page */

		for (col = 0; col < 128; col++)
			display_data(t0_logo[(col << 2) + (3 - row)]);
	}

	return 0;
}

static int do_display(struct cmd_tbl *cmdtp, int flag, int argc,
		      char *const argv[])
{
	struct udevice *bus;
	int ret;

	if (argc < 2)
		return CMD_RET_USAGE;

	/* Get I2C bus */
	ret = uclass_get_device_by_seq(UCLASS_I2C, DISPLAY_I2C_BUS, &bus);
	if (ret) {
		printf("Cannot find I2C bus %d: %d\n", DISPLAY_I2C_BUS, ret);
		return CMD_RET_FAILURE;
	}

	/* Get I2C chip */
	ret = i2c_get_chip(bus, DISPLAY_I2C_ADDR, 1, &display_dev);
	if (ret) {
		printf("Cannot access display at I2C 0x%x: %d\n",
		       DISPLAY_I2C_ADDR, ret);
		return CMD_RET_FAILURE;
	}

	/* Handle subcommands */
	if (strcmp(argv[1], "init") == 0) {
		ret = display_init();
		if (ret) {
			printf("Display initialization failed: %d\n", ret);
			return CMD_RET_FAILURE;
		}
		printf("Display initialized\n");
	} else if (strcmp(argv[1], "clear") == 0) {
		display_clear();
	} else if (strcmp(argv[1], "write") == 0) {
		if (argc < 3)
			return CMD_RET_USAGE;

		display_write_text(argv[2]);
	} else if (strcmp(argv[1], "logo") == 0) {
		display_draw_logo();
	} else if (strcmp(argv[1], "off") == 0) {
		display_command(SSD1306_DISPLAY_OFF);
	} else if (strcmp(argv[1], "on") == 0) {
		display_command(SSD1306_DISPLAY_ON);
	} else {
		return CMD_RET_USAGE;
	}

	return CMD_RET_SUCCESS;
}

U_BOOT_CMD(
	display, 3, 0, do_display,
	"control OLED display",
	"init                  - initialize display\n"
	"display clear                 - clear display\n"
	"display write <text>          - write text to bottom row\n"
	"display logo                  - display T0 logo\n"
	"display off                   - turn display off\n"
	"display on                    - turn display on\n"
	"  Hardware: I2C bus 2, address 0x3c (SSD1306 compatible)"
);
